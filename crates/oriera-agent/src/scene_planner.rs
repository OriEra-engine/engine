//! L9 场景编排:场景意图 → 确定性布局——真实场景批次 WP10。
//!
//! **本文件当前是骨架占位**:模块声明与 manifest 条目已由「真实场景批次
//! 骨架」PR 立好,实现由 WP10 填充。
//!
//! 职责:"说一句话,布好一个可进入的场景"里**模型之后**的那一半。模型
//! 只负责把一句话变成结构化的场景意图;布局是否放得下、朝向是否合理、
//! 相机是否看得到,由本模块用确定性算法保证——这是"提示词形状归引擎"
//! 在场景维度的延伸。
//!
//! 契约(填充时必须保持)
//! - 纯 std、wasm32 可编译,零新增依赖(serde 可用:意图与布局要能进
//!   场景 spec,沿用"实验即文件"的家规);
//! - **不调用任何模型**:输入是已结构化的场景意图 + 可用资产清单,
//!   输出是布局;本模块是纯函数;
//! - 摆放统一用 [`oriera_common::Transform`](#7 的跨层词汇,可直接
//!   序列化进场景 spec);
//! - 确定性:同种子同输入两次跑布局逐位一致(种子推进沿用仓库的 LCG
//!   约定,不用 `DefaultHasher`);输出顺序只取决于输入。

